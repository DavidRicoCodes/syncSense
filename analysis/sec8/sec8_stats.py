"""Section VIII numbers. Localization: pre-registered rule (3.36 cm, i.e. k = 1.12 on the 3.0 cm steering, modes A->B, B->A, both),
re-run with each run's pos9.py on its angle maps. Short windows, range, energy, fingerprint from the dashboard data
(generated by dash2/shortwin3.py, range9b.py, energy.py); sounding emulation from analysis/pulse_emu/results.jsonl."""
import json, os, sys, numpy as np
SP = "/tmp/claude-1000/-home-nextnet-sync/a6138dab-49bb-4e3a-be51-ab04509f60b6/scratchpad"
DD = os.path.expanduser("~/sync_backups/x410_two_ap_results_20261014/analysis/dashboard_detalle/data")
MODES = {"A->B": ("A→B",), "B->A": ("B→A",), "both": ("A→B", "B→A")}
R0 = 0.5                                 # AP exclusion radius (m); results without it: sec8_stats_noexcl.json
EX = os.path.expanduser("~/sync_backups/x410_two_ap_results_20261014/analysis/sec8/excl")
out = dict(loc={}, loc_summary=[], chance=None)
base = os.getcwd()
for run in ("t9", "t10", "t13", "t16"):
    os.chdir(f"{SP}/{run}"); sys.path.insert(0, os.getcwd()); sys.modules.pop("t9c", None)
    g = {}; exec(open("pos9.py").read().split("rng=np.random")[0], g)
    if out["chance"] is None:
        rng = np.random.default_rng(0); G, S, txy = g["G"], g["S"], g["tile_xy"]
        out["chance"] = float(np.median([np.linalg.norm(G[rng.integers(len(G))] - txy(*S[rng.integers(len(S))][3])) for _ in range(20000)]))
        out["geom"] = dict(A=g["CEN"]["A"].tolist(), B=g["CEN"]["B"].tolist(), grid=[float(g["G"][:, 0].min()), float(g["G"][:, 0].max()), float(g["G"][:, 1].min()), float(g["G"][:, 1].max())])
    # AP exclusion zone (2026-10-28, adopted after t16): no candidate within R0 of either AP; same for every run and mode
    g["G"] = g["G"][(np.linalg.norm(g["G"] - g["CEN"]["A"], axis=1) > R0) & (np.linalg.norm(g["G"] - g["CEN"]["B"], axis=1) > R0)]
    for mk, dirs in MODES.items():
        rows = []
        for nm, tl, p, er in g["errs"]({"A": 1.12, "B": 1.12}, dirs):
            tr = g["tile_xy"](*tl); rows.append(dict(order=int(nm.split(":")[0]), tile=list(tl), true=tr.tolist(), est=[float(p[0]), float(p[1])], err=float(er)))
        e = np.array([r["err"] for r in rows]); out["loc"][f"{run}|{mk}"] = rows
        out["loc_summary"].append(dict(run=run, mode=mk, median=float(np.median(e)), mean=float(e.mean()), max=float(e.max()), le30=int((e <= .3).sum()), le60=int((e <= .6).sum()), n=len(e)))
    sys.path.pop(0); os.chdir(base)
# short windows
# (excl/shortwin4.py = dashboard shortwin3.py with the same AP exclusion zone)
mm = {"A→B": "A->B", "B→A": "B->A", "ambos": "both", "A→B+B→A": "both"}; out["shortwin"] = []; out["shortpts"] = {}
for run in ("t9", "t10", "t13", "t16"):
    for key, r in json.load(open(f"{EX}/shortwin4_{run}.json")).items():
        w, md = key.split("|"); out["shortwin"].append(dict(run=run, window_s=float(w), mode=mm[md], windows=r["n"], median=r["median"], p80=r["p80"], p95=r["p95"], le30=r["le30"]))
    for r in json.load(open(f"{EX}/shortpts4_{run}.json")): out["shortpts"].setdefault(f"{r['run']}|{mm[r['mode']]}", []).append(r["error_m"])
# bistatic range
rg = json.load(open(f"{DD}/range.json")); out["range"] = {}
for run in ("t9", "t10", "t13", "t16"):
    rr = [r for r in rg if r["run"] == run]; real = np.array([r["real_m"] for r in rr])
    d = {}
    for k, key in (("A->B", "est_ab_m"), ("B->A", "est_ba_m")):
        est = np.array([r[key] for r in rr]); d[k] = dict(corr=float(np.corrcoef(real, est)[0, 1]), med_err=float(np.median(np.abs(est - real))), max_err=float(np.max(np.abs(est - real))))
    estb = np.array([(r["est_ab_m"] + r["est_ba_m"]) / 2 for r in rr]); d["mean of both"] = dict(corr=float(np.corrcoef(real, estb)[0, 1]), med_err=float(np.median(np.abs(estb - real))), max_err=float(np.max(np.abs(estb - real))))
    d["points"] = [dict(tile=r["tile"], real=r["real_m"], ab=r["est_ab_m"], ba=r["est_ba_m"]) for r in rr]
    out["range"][run] = d
# rear rejection and floor
en = json.load(open(f"{DD}/energy.json")); out["energy"] = {}
for run in ("t9", "t10", "t13", "t16"):
    e = {r["segment"]: (r["ab_db"], r["ba_db"]) for r in en if r["run"] == run}
    empty = np.nanmean([e[k] for k in e if k.startswith("vacío")], 0)
    tiles = np.array([v for k, v in e.items() if ":" in k]); fr = {"A": e.get("12:(3, 2)"), "B": e.get("13:(4, 3)")}; bh = {"A": e.get("detrás A"), "B": e.get("detrás B")}
    out["energy"][run] = dict(empty_floor_db=empty.tolist(), tiles_over_floor_db=[float(x) for x in np.median(tiles, 0) - empty],
                              front_over_empty={k: (np.array(fr[k]) - empty).tolist() for k in "AB"}, behind_over_empty={k: (np.array(bh[k]) - empty).tolist() for k in "AB"})
# antenna fingerprint (static rank-1 vector amplitudes) vs t9
fp = json.load(open(f"{DD}/fingerprint.json")); ref = {}
for r in fp:
    if r["run"] == "t9": ref[(r["direction"], r["side"], r["element"])] = r["amp"]
out["fingerprint_dev"] = {}
for run in ("t10", "t13", "t16"):
    dv = [abs(r["amp"] - ref[(r["direction"], r["side"], r["element"])]) for r in fp if r["run"] == run]
    out["fingerprint_dev"][run] = dict(mean=float(np.mean(dv)), max=float(np.max(dv)))
# sounding-length emulation
out["emulation"] = [json.loads(l) for l in open(os.path.expanduser("~/sync_backups/x410_two_ap_results_20261014/analysis/pulse_emu/results.jsonl"))]
EM = {(r["run"], r["npulse"]): r for r in json.load(open(f"{EX}/emu_excl.json"))}     # localization re-run with the exclusion zone
for r in out["emulation"]:
    for k_old, k_new in (("A→B", "A->B"), ("B→A", "B->A"), ("ambos", "both")): r[k_old] = EM[(r["run"], r["npulse"])][k_new]
json.dump(out, open("sec8_stats.json", "w"))
print("chance median", round(out["chance"], 2))
for r in out["loc_summary"]: print("LOC", r["run"], r["mode"], "median %.2f mean %.2f max %.2f <=0.3 %d/16 <=0.6 %d/16" % (r["median"], r["mean"], r["max"], r["le30"], r["le60"]))
for r in out["shortwin"]:
    if r["window_s"] in (0.5, 14.0): print("SW", r["run"], r["window_s"], r["mode"], "median %.2f p80 %.2f le30 %.0f%%" % (r["median"], r["p80"], 100 * r["le30"]))
for run, d in out["range"].items(): print("RANGE", run, {k: (round(v["corr"], 3), round(v["med_err"], 2), round(v["max_err"], 2)) for k, v in d.items() if k != "points"})
for run, d in out["energy"].items(): print("ENERGY", run, json.dumps(d))
print("FP", out["fingerprint_dev"])
# --- Remark 1 check: per-tile localization error vs per-tile inter-AP offset in t10 (offsets from Section VII stats,
#     per-tile medians over the same 14 s segments, sign e_AB = (l_B - l_A)/2)
from scipy.stats import spearmanr
S7 = json.load(open(f"{SP}/sec7/sec7_stats.json")); off = np.array([r for r in S7["runs"] if r["run"] == "t10_tiles"][0]["tile_medians"])
out["remark1_t10"] = {}
for mk in ("both", "A->B", "B->A"):
    err = np.array([r["err"] for r in out["loc"][f"t10|{mk}"]]); rho, pv = spearmanr(np.abs(off), err)
    out["remark1_t10"][mk] = dict(rho=float(rho), p=float(pv), worst_offset_ns=float(off[np.argmax(np.abs(off))]), err_at_worst=float(err[np.argmax(np.abs(off))]),
                                  max_err=float(err.max()), offsets_at_max_err=[float(off[i]) for i in np.flatnonzero(np.isclose(err, err.max()))])
    print("REMARK1", mk, out["remark1_t10"][mk])
json.dump(out, open("sec8_stats.json", "w"))
